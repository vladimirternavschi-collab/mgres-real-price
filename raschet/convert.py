def k(name):
    """Значение коэффициента."""
    return K[name]["v"]


def usd_per_mmbtu_to_usd_per_1000m3(x, teplotvornost=None):
    """$/mmbtu -> $/1000 м³ для биржевых индексов (по ВЫСШЕЙ теплоте сгорания)."""
    t = teplotvornost if teplotvornost is not None else k("теплотворность_для_индекса_МДж_м3")
    return x * (t * 1000.0) / K["мМБТЕ_в_МДж"]["v"]


def g_ut_to_m3(g_ut_per_kwh, teplotvornost=None):
    """г у.т./кВт·ч -> м³/кВт·ч по НИЗШЕЙ теплоте сгорания."""
    t = teplotvornost if teplotvornost is not None else k("теплотворность_низшая_МДж_м3")
    return g_ut_per_kwh / 1000.0 * K["кг_ут_в_МДж"]["v"] / t


def eur_per_tj_to_usd_per_1000m3(x, eurusd, teplotvornost=None):
    """€/ТДж -> $/1000 м³ по курсу EUR/USD за тот же месяц."""
    t = teplotvornost if teplotvornost is not None else k("теплотворность_для_индекса_МДж_м3")
    # 1000 м³ = t*1000 МДж = t*1e-3 ТДж
    return x * (t * 1e-3) * eurusd


def m3_20c_to_0c(v):
    return v * k("приведение_20C_к_0C")


def m3_to_kg(v):
    return v * k("плотность_газа_кг_м3")


def kg_to_m3(v):
    return v / k("плотность_газа_кг_м3")


def mw15_to_mwh(mw):
    return mw * k("мВтч_из_МВт_15мин")


# ------------------------------------------------------------------- курсы
_RATES = None


def _load_rates():
    global _RATES
    if _RATES is not None:
        return _RATES
    r = {"MDL/USD": [], "MDL/EUR": [], "USD/EUR": [], "RUP/USD": [], "RUP/EUR": []}
    with open(DATA / "kursy.csv", encoding="utf-8-sig") as fh:
        for row in csv.DictReader(fh):
            n, v, d = row["показатель"], float(row["значение"]), row["дата"]
            if n == "MDL за 1 USD":
                r["MDL/USD"].append((d, v))
            elif n == "MDL за 1 EUR":
                r["MDL/EUR"].append((d, v))
            elif n == "USD за 1 EUR":
                r["USD/EUR"].append((d, v))
            elif n.endswith("USD") and row["ряд"] == "ЦБ ПМР":
                r["RUP/USD"].append((d, v))
            elif n.endswith("EUR") and row["ряд"] == "ЦБ ПМР":
                r["RUP/EUR"].append((d, v))
    for kk in r:
        r[kk].sort()
    _RATES = r
    return r


def rate(pair, on_date):
    """Курс на дату; если точной даты нет - последняя предшествующая."""
    r = _load_rates()[pair]
    keys = [x[0] for x in r]
    i = bisect.bisect_right(keys, str(on_date)) - 1
    if i < 0:
        raise ValueError(f"нет курса {pair} на {on_date}")
    return r[i][1]


def rate_avg_year(pair, year):
    """Среднегодовой курс (среднее по всем наблюдениям года)."""
    r = _load_rates()[pair]
    vals = [v for d, v in r if d[:4] == str(year)]
    if not vals:
        raise ValueError(f"нет курса {pair} за {year}")
    return sum(vals) / len(vals)


def mdl_to_usd(v, on_date=None, year=None):
    return v / (rate("MDL/USD", on_date) if on_date else rate_avg_year("MDL/USD", year))


def usd_to_mdl(v, on_date=None, year=None):
    return v * (rate("MDL/USD", on_date) if on_date else rate_avg_year("MDL/USD", year))


def rup_to_usd(v, on_date=None):
    """Рубль ПМР -> доллар. Курс административный, с 05.04.2018 не меняется."""
    return v / (rate("RUP/USD", on_date) if on_date else k("курс_рубля_ПМР"))


